"""results.csv and results.tex from output/timing.json and output/budget.json (post-submission analyses).
Every row names its setting: event-level F1 under the contest rule (window [g-5, g+10], mistimed = FP + FN), integer
outputs, cross-fitted operating points, all 500 development clips (or the 100-clip public-test subset, which is part
of them), paired scene-bootstrap 95% intervals (183 or 70 scenes, 5000 resamples) with predictions held fixed.
Run from the repository root: python camera_ready/tables.py"""
import json
import pandas as pd
from common import OUT

T = json.loads((OUT / "timing.json").read_text())
B = json.loads((OUT / "budget.json").read_text())
rows = []
for g, r in T["groups"].items():
    for sp in ("all_500", "public_100"):
        a = r[sp]; d = a["learned_minus_constant"]
        rows.append(dict(experiment="TIMING", comparison="learned - constant timestamp (same emitted clips)", set=sp,
                         unit=f"submitted recipe, seed group {g} (3-seed OOF ensemble)", F1_a=a["learned"]["F1"],
                         F1_b=a["constant"]["F1"], dF1=d["dF1"], ci_lo=d["scene_ci95"][0], ci_hi=d["scene_ci95"][1],
                         counts_a=f"{a['learned']['TP']}/{a['learned']['FP']}/{a['learned']['FN']}",
                         counts_b=f"{a['constant']['TP']}/{a['constant']['FP']}/{a['constant']['FN']}",
                         note=f"emitted {a['emitted']}; in-window among emitted positives {a['learned']['timing_success_emitted_positives']} "
                              f"vs {a['constant']['timing_success_emitted_positives']}; of all positives "
                              f"{a['learned']['timing_success_all_positives']}"))
for name, gs in B["contrasts_group"].items():
    a_arm, b_arm = name.split("(")[1].rstrip(")").split(" - ")
    for g, x in gs.items():
        if g == "summary":
            continue
        for sp in ("all_500", "public_100"):
            ga, gb = B["groups"][f"{a_arm} {g}"], B["groups"][f"{b_arm} {g}"]
            rows.append(dict(experiment="BUDGET", comparison=name, set=sp, unit=f"seed group {g} (3-seed OOF ensemble)",
                             F1_a=ga[sp]["F1"], F1_b=gb[sp]["F1"], dF1=x[sp]["dF1"], ci_lo=x[sp]["scene_ci95"][0],
                             ci_hi=x[sp]["scene_ci95"][1], counts_a=f"{ga[sp]['TP']}/{ga[sp]['FP']}/{ga[sp]['FN']}",
                             counts_b=f"{gb[sp]['TP']}/{gb[sp]['FP']}/{gb[sp]['FN']}", note=""))
    for s, v in B["contrasts_seed"][name].items():
        rows.append(dict(experiment="SEEDS", comparison=name, set="all_500", unit=f"single seed {s}",
                         F1_a=B["seeds"][f"{a_arm} seed {s}"]["all_500"]["F1"], F1_b=B["seeds"][f"{b_arm} seed {s}"]["all_500"]["F1"],
                         dF1=v, ci_lo=None, ci_hi=None, counts_a="", counts_b="", note="no interval: seed-level spread only"))
X = pd.DataFrame(rows)
X.to_csv(OUT / "results.csv", index=False)

f = lambda v: "--" if v is None or v != v else f"{v:+.3f}"
L = [r"% Post-submission analyses, generated by camera_ready/tables.py.",
     r"\begin{tabular}{llccc}", r"\toprule", r"Group & Set & Learned & Constant & $\Delta$F1 [95\% CI] \\", r"\midrule"]
for r in X[X.experiment == "TIMING"].itertuples():
    L.append(f"{r.unit.split('group ')[1].split(' ')[0]} & {r.set.replace('_', ' ')} & {r.F1_a:.3f} & {r.F1_b:.3f} & "
             f"{f(r.dF1)} [{f(r.ci_lo)}, {f(r.ci_hi)}] \\\\")
L += [r"\bottomrule", r"\end{tabular}", "", r"\begin{tabular}{lllccc}", r"\toprule",
      r"Contrast & Group & Set & F1 (a) & F1 (b) & $\Delta$F1 [95\% CI] \\", r"\midrule"]
for r in X[X.experiment == "BUDGET"].itertuples():
    L.append(f"{r.comparison.split(' (')[0]} & {r.unit.split('group ')[1].split(' ')[0]} & {r.set.replace('_', ' ')} & "
             f"{r.F1_a:.3f} & {r.F1_b:.3f} & {f(r.dF1)} [{f(r.ci_lo)}, {f(r.ci_hi)}] \\\\")
L += [r"\bottomrule", r"\end{tabular}"]
(OUT / "results.tex").write_text("\n".join(L) + "\n")
print(X.groupby(["experiment", "set"]).size())
